import nodemailer from "nodemailer";
import type SMTPTransport from "nodemailer/lib/smtp-transport";

export type SendEmailInput = {
  to: string;
  subject: string;
  text: string;
  html?: string;
  replyTo?: string;
  /** Site-generated notification (contact form, job apply) */
  autoGenerated?: boolean;
  /** File attachments */
  attachments?: Array<{
    filename: string;
    content: Buffer;
    contentType?: string;
  }>;
};

function smtpConfigured(): boolean {
  return Boolean(process.env.SMTP_HOST?.trim() && process.env.SMTP_USER?.trim());
}

function smtpUser(): string {
  return process.env.SMTP_USER?.trim() ?? "";
}

function createTransport() {
  const port = Number(process.env.SMTP_PORT || "587");
  const secure =
    process.env.SMTP_SECURE === "true" || (process.env.SMTP_SECURE !== "false" && port === 465);

  const options: SMTPTransport.Options = {
    host: process.env.SMTP_HOST,
    port,
    secure,
    auth: {
      user: process.env.SMTP_USER,
      pass: process.env.SMTP_PASSWORD,
    },
    connectionTimeout: 20_000,
    greetingTimeout: 20_000,
    socketTimeout: 30_000,
    tls: {
      minVersion: "TLSv1.2",
    },
  };

  if (port === 587 && !secure) {
    options.requireTLS = true;
  }

  return nodemailer.createTransport(options);
}

function parseFrom(): string {
  const from = process.env.EMAIL_FROM?.trim();
  if (from) return from;
  const user = smtpUser();
  if (user) return `Mira Konnect <${user}>`;
  return "Mira Konnect <info@mirakonnect.com>";
}

function textToHtml(text: string): string {
  const escaped = text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
  return `<!DOCTYPE html><html><body style="font-family:Segoe UI,Arial,sans-serif;font-size:15px;line-height:1.5;color:#1a2b3c"><pre style="white-space:pre-wrap;font-family:inherit;margin:0">${escaped}</pre><p style="margin-top:24px;font-size:13px;color:#5c6b7a">Mira Konnect · mirakonnect.com</p></body></html>`;
}

function createProfessionalHtml(
  subject: string,
  content: string,
  jobTitle?: string,
  candidateName?: string,
): string {
  const lines = content.split('\n');
  let htmlContent = '';

  let inDetails = false;
  for (const line of lines) {
    if (line.includes('Application details:')) {
      inDetails = true;
      htmlContent += `<div style="background:#f8f9fa;padding:16px;border-radius:8px;margin:16px 0;">`;
      htmlContent += `<h3 style="margin:0 0 12px 0;font-size:14px;color:#1a2b3c;text-transform:uppercase;letter-spacing:0.5px;">Application Details</h3>`;
      continue;
    }
    if (line.trim() === '' && inDetails) {
      inDetails = false;
      htmlContent += `</div>`;
    }
    if (line.startsWith('Job:') || line.startsWith('Candidate:') || line.startsWith('Email:') || line.startsWith('Phone:') || line.startsWith('Current role:')) {
      const [label, ...valueParts] = line.split(':');
      const value = valueParts.join(':').trim();
      htmlContent += `<p style="margin:8px 0;color:#1a2b3c;"><strong style="color:#00bcd4;">${label}:</strong> ${value}</p>`;
    } else if (line.includes('http://') || line.includes('https://')) {
      htmlContent += `<p style="margin:8px 0;"><a href="${line.trim()}" style="color:#00bcd4;text-decoration:none;">${line.trim()}</a></p>`;
    } else if (line.trim()) {
      htmlContent += `<p style="margin:8px 0;color:#1a2b3c;">${line}</p>`;
    }
  }

  return `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${subject}</title>
</head>
<body style="margin:0;padding:0;font-family:'Segoe UI',Arial,sans-serif;background-color:#f4f4f4;">
  <div style="max-width:600px;margin:40px auto;background:#ffffff;border-radius:12px;box-shadow:0 2px 8px rgba(0,0,0,0.1);overflow:hidden;">
    <!-- Header -->
    <div style="background:linear-gradient(135deg,#1e4d7b 0%,#00bcd4 100%);padding:32px;">
      <h1 style="margin:0;color:#ffffff;font-size:24px;font-weight:600;">${subject}</h1>
      ${jobTitle ? `<p style="margin:8px 0 0 0;color:#ffffff;font-size:16px;opacity:0.9;">${jobTitle}</p>` : ''}
    </div>

    <!-- Content -->
    <div style="padding:32px;">
      ${htmlContent}

      <!-- Footer -->
      <div style="margin-top:32px;padding-top:24px;border-top:1px solid #e9ecef;">
        <p style="margin:0;color:#6c757d;font-size:13px;">
          <strong>Mira Konnect</strong><br>
          Professional Recruitment Services<br>
          <a href="https://mirakonnect.com" style="color:#00bcd4;text-decoration:none;">mirakonnect.com</a>
        </p>
      </div>
    </div>
  </div>
</body>
</html>`;
}

/**
 * Sends transactional email via SMTP when configured; otherwise logs in development.
 */
export async function sendTransactionalEmail(input: SendEmailInput): Promise<void> {
  if (!smtpConfigured()) {
    if (process.env.NODE_ENV === "development") {
      console.info("[email]", input.subject, "→", input.to);
      if (input.replyTo) console.info("  reply-to:", input.replyTo);
      console.info(input.text.slice(0, 500));
      if (input.attachments?.length) {
        console.info("  attachments:", input.attachments.map(a => a.filename).join(", "));
      }
    }
    return;
  }

  const user = smtpUser();
  const headers: Record<string, string> = {};
  if (input.autoGenerated) {
    headers["Auto-Submitted"] = "auto-generated";
  }

  const transport = createTransport();
  await transport.sendMail({
    from: parseFrom(),
    to: input.to,
    replyTo: input.replyTo ?? undefined,
    subject: input.subject,
    text: input.text,
    html: input.html ?? textToHtml(input.text),
    headers,
    envelope: {
      from: user,
      to: input.to,
    },
    attachments: input.attachments,
  });
}
