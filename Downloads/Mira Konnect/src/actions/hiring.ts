"use server";

import { getCurrentUser } from "@/lib/auth/get-user";
import { RoleName } from "@prisma/client";
import { revalidatePath } from "next/cache";
import { prisma } from "@/lib/db";
import { getNotificationInbox } from "@/lib/email/inbox";
import { sendTransactionalEmail } from "@/lib/email/send";
import { siteConfig } from "@/lib/site-config";

export type ActionResult = { ok: true } | { ok: false; error: string };

export async function submitHiringRequirementAction(formData: FormData): Promise<ActionResult> {
  const user = await getCurrentUser();
  if (!user?.employer || user.role.name !== RoleName.EMPLOYER) {
    return { ok: false, error: "Employer account required" };
  }

  const title = String(formData.get("title") ?? "").trim();
  const description = String(formData.get("description") ?? "").trim();
  if (!title || !description) {
    return { ok: false, error: "Title and description are required" };
  }

  const industry = String(formData.get("industry") ?? "") || undefined;
  const location = String(formData.get("location") ?? "") || undefined;
  const positions = Number(formData.get("positions") ?? 1) || 1;
  const expectedTimeline = String(formData.get("expectedTimeline") ?? "") || undefined;

  await prisma.hiringRequirement.create({
    data: {
      employerId: user.employer.id,
      title,
      description,
      industry,
      location,
      positions,
      expectedTimeline,
    },
  });

  /* ── Email notifications ── */
  const inbox = getNotificationInbox();
  const companyName = user.employer.company?.name ?? "Unknown company";
  const adminUrl = `${siteConfig.url}/admin/requirements`;

  const teamText = [
    "New hiring requirement on Mira Konnect",
    "",
    `Company: ${companyName}`,
    `Contact: ${user.name} (${user.email})`,
    user.phone ? `Phone: ${user.phone}` : null,
    "",
    `Role title: ${title}`,
    `Positions: ${positions}`,
    industry ? `Industry: ${industry}` : null,
    location ? `Location: ${location}` : null,
    expectedTimeline ? `Expected timeline: ${expectedTimeline}` : null,
    "",
    "Description:",
    description,
    "",
    `Review in admin: ${adminUrl}`,
  ]
    .filter(Boolean)
    .join("\n");

  try {
    await sendTransactionalEmail({
      to: inbox,
      replyTo: user.email,
      subject: `Hiring requirement: ${title} (${companyName})`,
      text: teamText,
      autoGenerated: true,
    });

    await sendTransactionalEmail({
      to: user.email,
      subject: `Hiring requirement received — ${title}`,
      text: `Hi ${user.name},\n\nThank you for submitting your hiring requirement for "${title}". Our team will review it and reach out to discuss next steps.\n\n— Mira Konnect\ninfo@mirakonnect.com`,
    });
  } catch (err) {
    console.error("[email] hiring requirement notification failed:", err);
  }

  revalidatePath("/employer/requirements");
  revalidatePath("/admin/leads");
  return { ok: true };
}
