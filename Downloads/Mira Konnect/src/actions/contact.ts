"use server";

import { revalidatePath } from "next/cache";
import { getNotificationInbox } from "@/lib/email/inbox";
import { sendTransactionalEmail } from "@/lib/email/send";
import { prisma } from "@/lib/db";
import { contactSchema } from "@/lib/validations/contact";

export type ActionResult = { ok: true } | { ok: false; error: string };

export async function submitContactAction(formData: FormData): Promise<ActionResult> {
  const parsed = contactSchema.safeParse({
    name: formData.get("name"),
    email: formData.get("email"),
    phone: formData.get("phone") || undefined,
    company: formData.get("company") || undefined,
    subject: formData.get("subject") || undefined,
    message: formData.get("message"),
  });
  if (!parsed.success) {
    return { ok: false, error: parsed.error.issues[0]?.message ?? "Invalid input" };
  }

  const data = parsed.data;
  const inbox = getNotificationInbox();

  await prisma.contactLead.create({
    data: {
      name: data.name,
      email: data.email.toLowerCase(),
      phone: data.phone,
      company: data.company,
      subject: data.subject,
      message: data.message,
    },
  });

  const subjectLine = data.subject?.trim() || "Website contact form";
  const teamText = [
    "New message from the Mira Konnect contact form",
    "",
    `Name: ${data.name}`,
    `Email: ${data.email}`,
    data.phone ? `Phone: ${data.phone}` : null,
    data.company ? `Company: ${data.company}` : null,
    `Subject: ${subjectLine}`,
    "",
    "Message:",
    data.message,
  ]
    .filter(Boolean)
    .join("\n");

  try {
    await sendTransactionalEmail({
      to: inbox,
      replyTo: data.email,
      subject: `Website contact: ${subjectLine} (${data.name})`,
      text: teamText,
      autoGenerated: true,
    });

    try {
      await sendTransactionalEmail({
        to: data.email,
        replyTo: inbox,
        subject: "We received your message — Mira Konnect",
        text: `Hi ${data.name},\n\nThank you for contacting Mira Konnect. Our team will respond shortly.\n\n— Mira Konnect\ninfo@mirakonnect.com`,
      });
    } catch (confirmErr) {
      console.error("[email] contact confirmation failed:", confirmErr);
    }
  } catch (err) {
    console.error("[email] contact notification failed:", err);
    return {
      ok: false,
      error:
        "We saved your message, but could not send email from the server. If you're on a local PC, try SMTP_PORT=587 in .env or test again on your live Hostinger site.",
    };
  }

  revalidatePath("/admin/leads");
  return { ok: true };
}
